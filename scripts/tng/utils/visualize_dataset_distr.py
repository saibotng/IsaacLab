#!/usr/bin/env python3
"""
plot_cases_yaml.py

Read a cases YAML (as generated by generate_cases_yaml.py) and create three plots:
  1) Scatter of all object positions
  2) Scatter of all target positions
  3) Line per case connecting object -> target

Each plot is saved as a PNG in the same directory as the input file (filenames printed on stdout).

Usage:
  python plot_cases_yaml.py --in cases.yaml

Optional:
  --pad 0.05     # extra margin added to inferred plot limits
  --show         # display the plots interactively as well
"""

import argparse
import os
import yaml
import matplotlib.pyplot as plt


def infer_dim(points, pad=0.05):
    """Infer square bounds from points and add a padding margin."""
    if not points:
        return (-1, 1)  # fallback
    xs = [p[0] for p in points]
    ys = [p[1] for p in points]
    m = max(max(abs(min(xs)), abs(max(xs))), max(abs(min(ys)), abs(max(ys))))
    d = m * (1.0 + pad)
    return (-d, d)


def load_positions(yaml_path):
    with open(yaml_path, "r", encoding="utf-8") as f:
        doc = yaml.safe_load(f)
    cases = doc.get("test_cases", [])

    obj_pts = []
    tgt_pts = []
    lines = []  # ( (ox,oy), (tx,ty) )

    for c in cases:
        ox, oy, _ = c["object"]["pos"]
        tx, ty, _ = c["target"]["pos"]
        obj_pts.append((ox, oy))
        tgt_pts.append((tx, ty))
        lines.append(((ox, oy), (tx, ty)))

    return obj_pts, tgt_pts, lines


def scatter_plot(points, title, outfile, xlim=None, ylim=None):
    plt.figure()
    xs = [p[0] for p in points]
    ys = [p[1] for p in points]
    plt.scatter(xs, ys, s=12)
    plt.xlabel("x")
    plt.ylabel("y")
    plt.title(title)
    plt.gca().set_aspect("equal", adjustable="box")
    if xlim and ylim:
        plt.xlim(*xlim)
        plt.ylim(*ylim)
    # draw square boundary if limits are equal & symmetric
    if xlim and ylim and abs(xlim[0]) == abs(xlim[1]) and abs(ylim[0]) == abs(ylim[1]):
        d = xlim[1]
        plt.plot([-d, d, d, -d, -d], [d, d, -d, -d, d], linewidth=1)
    plt.grid(True, linewidth=0.3, alpha=0.4)
    plt.tight_layout()
    plt.savefig(outfile, dpi=150)
    plt.close()


def line_plot(lines, title, outfile, xlim=None, ylim=None):
    plt.figure()
    for (o, t) in lines:
        xs = [o[0], t[0]]
        ys = [o[1], t[1]]
        plt.plot(xs, ys, linewidth=0.7)
    plt.xlabel("x")
    plt.ylabel("y")
    plt.title(title)
    plt.gca().set_aspect("equal", adjustable="box")
    if xlim and ylim:
        plt.xlim(*xlim)
        plt.ylim(*ylim)
    if xlim and ylim and abs(xlim[0]) == abs(xlim[1]) and abs(ylim[0]) == abs(ylim[1]):
        d = xlim[1]
        plt.plot([-d, d, d, -d, -d], [d, d, -d, -d, d], linewidth=1)
    plt.grid(True, linewidth=0.3, alpha=0.4)
    plt.tight_layout()
    plt.savefig(outfile, dpi=150)
    plt.close()


def main():
    ap = argparse.ArgumentParser(description="Plot object/target distributions and connections from YAML.")
    ap.add_argument("--in", dest="infile", required=True, help="Input YAML filepath.")
    ap.add_argument("--pad", type=float, default=0.05, help="Relative padding for inferred square bounds.")
    ap.add_argument("--show", action="store_true", help="Also show plots interactively.")
    args = ap.parse_args()

    obj_pts, tgt_pts, lines = load_positions(args.infile)
    all_pts = obj_pts + tgt_pts
    xlim = ylim = infer_dim(all_pts, pad=args.pad)

    base = os.path.splitext(os.path.basename(args.infile))[0]
    out_dir = os.path.dirname(os.path.abspath(args.infile)) or "."
    out1 = os.path.join(out_dir, f"{base}_objects.png")
    out2 = os.path.join(out_dir, f"{base}_targets.png")
    out3 = os.path.join(out_dir, f"{base}_connections.png")

    scatter_plot(obj_pts, "Object position distribution", out1, xlim, ylim)
    scatter_plot(tgt_pts, "Target position distribution", out2, xlim, ylim)
    line_plot(lines, "Object→Target connections (per case)", out3, xlim, ylim)

    print("Saved plots:")
    print("  ", out1)
    print("  ", out2)
    print("  ", out3)

    if args.show:
        # If user requests showing, re-render quickly to interactive windows.
        import matplotlib.pyplot as plt
        # 1
        xs = [p[0] for p in obj_pts]; ys = [p[1] for p in obj_pts]
        plt.figure(); plt.scatter(xs, ys, s=12); plt.gca().set_aspect("equal"); plt.xlim(*xlim); plt.ylim(*ylim); plt.title("Object positions"); plt.grid(True, linewidth=0.3, alpha=0.4)
        # 2
        xs = [p[0] for p in tgt_pts]; ys = [p[1] for p in tgt_pts]
        plt.figure(); plt.scatter(xs, ys, s=12); plt.gca().set_aspect("equal"); plt.xlim(*xlim); plt.ylim(*ylim); plt.title("Target positions"); plt.grid(True, linewidth=0.3, alpha=0.4)
        # 3
        plt.figure()
        for (o, t) in lines:
            plt.plot([o[0], t[0]], [o[1], t[1]], linewidth=0.7)
        plt.gca().set_aspect("equal"); plt.xlim(*xlim); plt.ylim(*ylim); plt.title("Object→Target connections"); plt.grid(True, linewidth=0.3, alpha=0.4)
        plt.show()


if __name__ == "__main__":
    main()
